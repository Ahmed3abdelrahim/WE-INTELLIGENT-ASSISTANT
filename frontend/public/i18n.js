const I18n = {
  lang: "en",

  t(key, ...args) {
    const value = (STRINGS[this.lang] || STRINGS.en)[key] ?? STRINGS.en[key] ?? key;
    return typeof value === "function" ? value(...args) : value;
  },

  // Fill every element marked data-i18n / data-i18n-placeholder / data-i18n-title.
  apply(lang) {
    this.lang = STRINGS[lang] ? lang : "en";
    const root = document.documentElement;
    root.lang = this.lang;
    root.dir = this.lang === "ar" ? "rtl" : "ltr";
    document.title = this.t("appTitle");
    document.querySelectorAll("[data-i18n]").forEach((n) => (n.textContent = this.t(n.dataset.i18n)));
    document.querySelectorAll("[data-i18n-placeholder]").forEach((n) => (n.placeholder = this.t(n.dataset.i18nPlaceholder)));
    document.querySelectorAll("[data-i18n-title]").forEach((n) => {
      n.title = this.t(n.dataset.i18nTitle);
      n.setAttribute("aria-label", n.title);
    });
  },
};
const t = (key, ...args) => I18n.t(key, ...args);
