#!/usr/bin/env python3
"""ASR accuracy: WER/CER of faster-whisper on a manifest of clips (SPEC.md section 10).

Compares large-v3-turbo vs large-v3, beam 1 vs 5, with vs without the telecom hotwords
(config/asr_hotwords.txt), overall and per language/condition, plus real-time factor.

  Real clips (the numbers that count):  fill eval/audio_manifest.jsonl (see
      eval/RECORDING_CHECKLIST.md), then:  python eval/asr_eval.py
  Synthetic plumbing check:  python scripts/make_synthetic_clips.py --manifest
      python eval/asr_eval.py --manifest eval/audio_manifest.synthetic.jsonl --out eval/results_asr_synthetic.md

Loads the models in-process (one at a time); on a 10 GB GPU stop the backend and ASR service
first, or set ASR_DEVICE=cpu ASR_COMPUTE_TYPE=int8 (slow).
"""
import argparse
import gc
import json
import os
import statistics
import sys
import time
import wave
from collections import defaultdict

import jiwer
from faster_whisper import WhisperModel

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "backend"))
from app.generation.smalltalk import normalize as normalize_ar  # noqa: E402

AUDIO_DIR = os.path.join(REPO_ROOT, "eval", "audio")
MODELS = ["large-v3-turbo", "large-v3"]
DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")


def normalize(text: str) -> str:
    """Score words, not formatting: Arabic letter variants, diacritics, punctuation, digits."""
    return normalize_ar(text.translate(DIGITS))


def load_manifest(path):
    with open(path, encoding="utf-8") as f:
        rows = [json.loads(line) for line in f if line.strip()]
    usable = [r for r in rows if r.get("transcript") and os.path.isfile(os.path.join(AUDIO_DIR, r["filename"]))]
    skipped = [r["id"] for r in rows if r not in usable]
    return usable, skipped


def duration_s(path):
    try:
        with wave.open(path) as w:
            return w.getnframes() / w.getframerate()
    except wave.Error:
        return None  # non-wav (m4a/webm/mp3): faster-whisper decodes it, RTF just isn't reported


def hotwords():
    with open(os.path.join(REPO_ROOT, "config", "asr_hotwords.txt"), encoding="utf-8") as f:
        return ", ".join(ln.strip() for ln in f if ln.strip() and not ln.startswith("#"))


def run(clips, device, compute_type):
    results = []  # (config, clip, hypothesis, seconds)
    hw = hotwords()
    for name in MODELS:
        path = os.path.join(REPO_ROOT, "models", "asr", name)
        if not os.path.isdir(path):
            print(f"skip {name}: {path} not found")
            continue
        model = WhisperModel(path, device=device, compute_type=compute_type)
        for beam in (1, 5):
            for use_hw in (False, True):
                cfg = f"{name} · beam {beam} · hotwords {'on' if use_hw else 'off'}"
                for clip in clips:
                    t0 = time.time()
                    segments, _ = model.transcribe(
                        os.path.join(AUDIO_DIR, clip["filename"]), language=clip.get("lang") or None,
                        beam_size=beam, vad_filter=True, condition_on_previous_text=False,
                        hotwords=hw if use_hw else None,
                    )
                    hyp = "".join(s.text for s in segments).strip()
                    results.append((cfg, clip, hyp, time.time() - t0))
                print(f"done: {cfg}", flush=True)
        del model
        gc.collect()
    return results


def score(pairs):
    refs = [normalize(c["transcript"]) for c, _ in pairs]
    hyps = [normalize(h) for _, h in pairs]
    return jiwer.wer(refs, hyps), jiwer.cer(refs, hyps)


def report(results, manifest, skipped, out, device, compute_type):
    by_cfg = defaultdict(list)
    for cfg, clip, hyp, secs in results:
        by_cfg[cfg].append((clip, hyp, secs))
    synthetic = "synthetic" in os.path.basename(manifest)
    lines = [f"# ASR accuracy{' — SYNTHETIC clips (plumbing check, not real speech)' if synthetic else ''}\n",
             f"Generated by `eval/asr_eval.py` from `{os.path.relpath(manifest, REPO_ROOT)}` "
             f"({len(next(iter(by_cfg.values()), []))} clips) on {device}/{compute_type}. "
             "WER/CER after normalisation (Arabic letter variants, diacritics, punctuation, digits).\n"]
    if synthetic:
        lines.append("> These clips are Piper TTS speech (one Jordanian-Arabic and one US-English voice), so they "
                     "measure the pipeline, not real callers: no real Egyptian accent, no real background noise "
                     "(noise is synthetic), no spontaneous speech. Real numbers come from "
                     "`eval/audio_manifest.jsonl` — see `eval/RECORDING_CHECKLIST.md`.\n")
    if skipped:
        lines.append(f"Skipped (no transcript or audio file): {', '.join(skipped)}\n")

    lines.append("\n## Overall\n\n| Config | WER | CER | RTF (lower = faster) |\n|---|---|---|---|\n")
    best = None
    for cfg, rows in by_cfg.items():
        wer, cer = score([(c, h) for c, h, _ in rows])
        rtfs = [s / d for c, _, s in rows if (d := duration_s(os.path.join(AUDIO_DIR, c["filename"])))]
        rtf = f"{statistics.mean(rtfs):.3f}" if rtfs else "—"
        lines.append(f"| {cfg} | {wer:.1%} | {cer:.1%} | {rtf} |\n")
        if best is None or wer < best[1]:
            best = (cfg, wer)

    groups = sorted({(c["lang"], c.get("condition", "")) for c, _, _ in next(iter(by_cfg.values()))})
    lines.append("\n## By language and condition (WER)\n\n| Config | " + " | ".join(f"{l}/{cond}" for l, cond in groups) + " |\n")
    lines.append("|---|" + "---|" * len(groups) + "\n")
    for cfg, rows in by_cfg.items():
        cells = []
        for g in groups:
            sel = [(c, h) for c, h, _ in rows if (c["lang"], c.get("condition", "")) == g]
            cells.append(f"{score(sel)[0]:.0%}")
        lines.append(f"| {cfg} | " + " | ".join(cells) + " |\n")

    deployed = "large-v3-turbo · beam 1 · hotwords on"  # what the backend's /transcribe uses
    lines.append(f"\n## Per clip ({deployed} — the deployed setting)\n\n| Clip | Reference | Heard |\n|---|---|---|\n")
    for c, h, _ in by_cfg.get(deployed, []):
        lines.append(f"| {c['id']} ({c['lang']}/{c.get('condition', '')}) | {c['transcript']} | {h} |\n")
    if best:
        lines.append(f"\nLowest WER: **{best[0]}** ({best[1]:.1%}).\n")
    with open(out, "w", encoding="utf-8") as f:
        f.writelines(lines)
    print(f"wrote {out}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", default=os.path.join(REPO_ROOT, "eval", "audio_manifest.jsonl"))
    ap.add_argument("--out", default=os.path.join(REPO_ROOT, "eval", "results_asr.md"))
    args = ap.parse_args()
    if not os.path.isfile(args.manifest):
        sys.exit(f"{args.manifest} not found — record the clips (eval/RECORDING_CHECKLIST.md) first")
    clips, skipped = load_manifest(args.manifest)
    if not clips:
        sys.exit("no usable clips (each needs an audio file in eval/audio/ and a transcript)")
    device = os.environ.get("ASR_DEVICE", "cuda")
    compute_type = os.environ.get("ASR_COMPUTE_TYPE", "float16" if device == "cuda" else "int8")
    report(run(clips, device, compute_type), args.manifest, skipped, args.out, device, compute_type)


if __name__ == "__main__":
    main()
